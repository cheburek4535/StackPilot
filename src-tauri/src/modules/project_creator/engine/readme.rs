/// Связь фреймворка с остальными компонентами (контекстно-зависимая).
fn framework_relationship(ctx: &ReadmeContext, fw: &str) -> String {
    let shell = embedded_shell(ctx);
    // Qt WebEngine встраивает веб-фронтенд — специфичный текст ДО общего
    // описания оболочки, иначе ветка `fw == "qt"` перехватит его первой.
    if qt_is_webengine(ctx) && matches!(fw, "qt" | "qt-webengine") {
        let web = ctx
            .context
            .frameworks
            .iter()
            .find(|f| is_web_frontend(f))
            .map(|f| framework_name(f).to_string())
            .unwrap_or_else(|| "the web UI".to_string());
        return format!(
            "Qt WebEngine mode embeds {} in a native window — it is not a standalone \
             website, the frontend is packaged into the desktop app.",
            web
        );
    }
    if let Some(shell_label) = shell {
        if fw == "tauri" || fw == "qt" || fw.starts_with("qt-") {
            return format!(
                "{} is the desktop shell of this project — it hosts the native window \
                 and embeds the web frontend.",
                framework_name(fw)
            );
        }
        if is_web_frontend(fw) {
            return format!(
                "Embedded UI: this frontend is rendered inside the {} shell and is \
                 **not** a standalone website. It is built into the shell rather than \
                 deployed separately.",
                shell_label
            );
        }
    }
    // Неинтегрированные клиентские оболочки (electron, expo, react-native,
    // plasmo) НЕ встроены в корень проекта: они standalone-клиенты,
    // общающиеся с API по HTTP (LayoutClass::ShellClientApi / FrontendOnly).
    if matches!(fw, "electron" | "expo" | "react-native" | "plasmo") {
        return "A client shell: a standalone desktop/mobile application that hosts its own \
                UI. It is not embedded into another shell and can be deployed independently."
            .to_string();
    }
    let frontends: Vec<&str> = ctx
        .context
        .frameworks
        .iter()
        .map(String::as_str)
        .filter(|f| is_web_frontend(f))
        .collect();
    let backends: Vec<&str> = ctx
        .context
        .frameworks
        .iter()
        .map(String::as_str)
        .filter(|f| is_backend_framework(f))
        .collect();
    if backends.iter().any(|b| b == &fw) && !frontends.is_empty() && shell.is_none() {
        return format!(
            "Serves the API consumed by the {} frontend.",
            join_and(
                &frontends
                    .iter()
                    .map(|f| framework_name(f).to_string())
                    .collect::<Vec<_>>()
            )
        );
    }
    if is_web_frontend(fw) && !backends.is_empty() && shell.is_none() {
        return format!(
            "Consumes the API provided by {}.",
            join_and(
                &backends
                    .iter()
                    .map(|b| framework_name(b).to_string())
                    .collect::<Vec<_>>()
            )
        );
    }
    if matches!(fw, "aiogram" | "telegraf") {
        return "A companion service that runs alongside the main application and listens \
                to Telegram updates."
            .to_string();
    }
    if is_backend_framework(fw) && architecture(ctx) == Architecture::FrontendOnly {
        return "Runs as part of this project; there is no separate browser side to serve — \
                this is a server/CLI runtime."
            .to_string();
    }
    if matches!(
        fw,
        "nextjs" | "nuxt" | "sveltekit" | "phoenix" | "laravel" | "solidjs"
    ) && backends.is_empty()
        && shell.is_none()
    {
        return "Includes its own server and can serve both the UI and the API from the same \
                process — it does not depend on a separate backend."
            .to_string();
    }
    format!(
        "Runs as part of the {} project stack.",
        architecture(ctx).label()
    )
}

