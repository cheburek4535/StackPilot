fn section_docker(ctx: &ReadmeContext, doc: &mut ReadmeDoc) {
    if !ctx.context.docker {
        doc.add(
            "Docker usage",
            "Docker is **not** configured for this project. Regenerate it with the Docker \
             feature enabled to get a `Dockerfile` and (when infrastructure services are \
             selected) a `docker-compose.yaml`.",
        );
        return;
    }
    let docker_tools = docker_managed_tools(ctx);
    if docker_tools.is_empty() {
        let mut body = String::new();
        body.push_str(
            "The project ships a `Dockerfile` for the application image, but no \
             infrastructure services are managed by Docker — every selected service runs \
             locally instead.\n\n",
        );
        if !local_tools(ctx).is_empty() {
            body.push_str(
                "Start those services first (see LOCAL_INFRA.md), then build the \
                           app image:\n\n```\ndocker build -t <name> .\n```\n",
            );
        } else {
            body.push_str(
                "Build the app image when you need it:\n\n```\ndocker build -t <name> .\n```\n",
            );
        }
        doc.add("Docker usage", body);
        return;
    }
    let mut body = String::new();
    body.push_str(&format!(
        "The infrastructure services are managed by **Docker Compose** (see \
         `docker-compose.yaml`): {}.\n\n",
        docker_tools
            .iter()
            .map(|t| tool_name(t))
            .collect::<Vec<_>>()
            .join(", ")
    ));
    // The compose file also carries the app service. Starting ONLY the infra
    // services (`up -d <services>`) is the right command for a dev session:
    // the full `up -d` would publish the app container on the same host port
    // the local dev server binds.
    let infra_services: Vec<String> = docker_tools
        .iter()
        .filter_map(|t| crate::ports::tool_service_name(t))
        .map(String::from)
        .collect();
    let infra_up = if infra_services.is_empty() {
        "docker compose up -d".to_string()
    } else {
        format!("docker compose up -d {}", infra_services.join(" "))
    };
    body.push_str(
        "Start everything (services + the app) — a full containerized run:\n\n```\ndocker compose up --build\n```\n\n",
    );
    body.push_str(&format!(
        "Start only the infrastructure services in the background (the app runs locally \
         during development):\n\n```\n{}\n```\n\n",
        infra_up
    ));
    body.push_str("Stop and remove the containers:\n\n```\ndocker compose down\n```\n\n");
    body.push_str("Watch the app logs:\n\n```\ndocker compose logs -f app\n```\n\n");
    let local = local_tools(ctx);
    if !local.is_empty() {
        body.push_str(&format!(
            "Note: {} run **locally**, not in Docker — do not look for their containers in \
             `docker compose ps`.\n",
            local
                .iter()
                .map(|t| tool_name(t))
                .collect::<Vec<_>>()
                .join(", ")
        ));
    }
    doc.add("Docker usage", body);
}

